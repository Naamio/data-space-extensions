//! The text path: a component writes the statements a document makes as Turtle, and the
//! host parses that text into the dataset.
//!
//! This is the alternative to the contract that the benchmark measures. The component runs
//! the same Turtle grammar as the typed path does. Instead of streaming typed statements, it
//! writes them back out as normalised Turtle: prefixed names, relative references and blank
//! node labels stay exactly as the document wrote them, so the host still does all the
//! interpreting, as it does on the typed path. The host then parses the text with
//! [`native::read_turtle`].
//!
//! The component runs on the same engine configuration and the same WebAssembly System
//! Interface (WASI) linking as the extension host, and each parse runs in a new instance,
//! as the host's do. The two paths therefore differ only in the form the statements take
//! when they cross the boundary.

use std::error::Error;
use std::fmt;
use std::pin::Pin;
use std::sync::{Arc, Mutex, PoisonError};
use std::task::{Context, Poll};

use linked_data::dataset::Dataset;
use tokio::sync::oneshot;
use wasmtime::component::{
	Component, FutureConsumer, Linker, ResourceTable, Source, StreamConsumer, StreamReader,
	StreamResult,
};
use wasmtime::{Config, Engine, Store, StoreContextMut};
use wasmtime_wasi::{WasiCtx, WasiCtxView, WasiView};

use crate::native;

/// Rust bindings for the benchmark's `text-parser-component` world, generated by Wasmtime
/// from `wit/text-parser.wit` when the crate compiles.
///
/// The exports are generated as functions that take the store's accessor, as the extension
/// host's are. The component returns its byte stream at once and writes to it from a task it
/// spawns, and that task makes progress only while the store's event loop runs, so the call
/// and the reading of the stream both happen inside one `run_concurrent`.
mod bindings {
	wasmtime::component::bindgen!({
		path: "wit",
		world: "text-parser-component",
		exports: { default: async | store },
	});
}

/// A failure of the text path to produce a dataset.
///
/// The message names the side at fault: the component, which may have refused the document
/// or failed while running, or the host, which may have been unable to parse the Turtle the
/// component wrote.
#[derive(Debug)]
pub struct TextError(String);

impl fmt::Display for TextError {
	fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
		formatter.write_str(&self.0)
	}
}

impl Error for TextError {}

/// A failure Wasmtime reports while compiling, linking, instantiating or running the
/// component. The alternate format includes the chain of causes, which usually names the
/// import or export at fault.
impl From<wasmtime::Error> for TextError {
	fn from(error: wasmtime::Error) -> Self {
		Self(format!("the component failed: {error:#}"))
	}
}

/// A failure parsing the component's Turtle in the host. On a document the component
/// accepted, this means the component wrote text that is not valid Turtle.
impl From<native::NativeError> for TextError {
	fn from(error: native::NativeError) -> Self {
		Self(format!(
			"the host could not parse the component's text: {error}"
		))
	}
}

/// The data a Wasmtime store holds for one instance of the component.
///
/// It matches the extension host's own instance state, which the host keeps private: a WASI
/// context built empty, so the component sees no files, environment, network or standard
/// streams, and a table for the resources it holds handles to. Granting the same nothing as
/// the host keeps the comparison fair.
struct InstanceState {
	/// The WASI context, built with no capabilities.
	wasi: WasiCtx,
	/// The resources the instance holds handles to, including the streams and the future of
	/// a parse in progress.
	table: ResourceTable,
}

/// Gives Wasmtime's WASI implementation the context and resource table it works on.
impl WasiView for InstanceState {
	fn ctx(&mut self) -> WasiCtxView<'_> {
		WasiCtxView {
			ctx: &mut self.wasi,
			table: &mut self.table,
		}
	}
}

/// A compiled text-path component, ready to run each parse in a new instance.
///
/// Compiling is the slow step, so a benchmark loads the component once and times only the
/// parses, as it does for the extension host's parser components.
pub struct TextParserComponent {
	/// The engine the component was compiled with, which every new store must share.
	engine: Engine,
	/// The component, already linked, so a parse only has to instantiate it.
	prepared: bindings::TextParserComponentPre<InstanceState>,
}

/// Prints the type name only. The engine and the prepared component hold nothing that a
/// reader of a debug message could use.
impl fmt::Debug for TextParserComponent {
	fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
		formatter
			.debug_struct("TextParserComponent")
			.finish_non_exhaustive()
	}
}

impl TextParserComponent {
	/// Compiles `component` and links it against WASI 0.2 and 0.3, with the component
	/// model's asynchronous features turned on, exactly as the extension host configures its
	/// engine and linker.
	///
	/// # Errors
	///
	/// Returns an error if `component` is not a valid component, imports an interface the
	/// linker does not provide, or does not export the `text-parser` interface.
	pub fn load(component: &[u8]) -> Result<Self, TextError> {
		let mut configuration = Config::new();
		configuration.wasm_component_model_async(true);
		let engine = Engine::new(&configuration)?;

		let mut linker = Linker::new(&engine);
		wasmtime_wasi::p2::add_to_linker_async(&mut linker)?;
		wasmtime_wasi::p3::add_to_linker(&mut linker)?;
		let component = Component::new(&engine, component)?;
		let prepared = bindings::TextParserComponentPre::new(linker.instantiate_pre(&component)?)?;

		Ok(Self { engine, prepared })
	}

	/// Runs the whole text path: the component writes the statements `document` makes as
	/// Turtle, and the host parses that Turtle against `base` into `dataset`.
	///
	/// Returns how many quads were new to the dataset, which the benchmark compares with the
	/// number of triples the document states.
	///
	/// # Errors
	///
	/// Returns the component's error if it refuses the document or fails, or the host's if
	/// it cannot parse the text the component wrote.
	pub async fn parse(
		&self,
		document: &[u8],
		base: &str,
		dataset: &mut Dataset,
	) -> Result<usize, TextError> {
		let text = self.write_text(document).await?;
		Ok(native::read_turtle(&text, base, dataset)?)
	}

	/// Runs the component's half of the text path over `document`, and returns the Turtle
	/// it writes.
	///
	/// # Errors
	///
	/// Returns the component's error message if it refuses the document, or a Wasmtime
	/// error if the component fails or ends without reporting an outcome.
	pub async fn write_text(&self, document: &[u8]) -> Result<Vec<u8>, TextError> {
		let mut store = Store::new(
			&self.engine,
			InstanceState {
				wasi: WasiCtx::builder().build(),
				table: ResourceTable::new(),
			},
		);
		let instance = self.prepared.instantiate_async(&mut store).await?;
		let parser = instance.naamio_benchmarks_text_parser();
		let document = StreamReader::new(&mut store, document.to_vec())?;
		let text = Arc::new(Mutex::new(Vec::new()));
		let consumer = ByteConsumer {
			bytes: Arc::clone(&text),
		};

		// The call, the attaching of the consumers and the wait for the outcome all happen
		// inside one `run_concurrent`, for the reason given on the bindings: the component
		// writes from a task that runs only while the store's event loop does.
		let outcome = store
			.run_concurrent(async |accessor| -> Result<Result<(), String>, TextError> {
				let (bytes, outcome) = parser.call_parse(accessor, document).await?;
				let (sender, receiver) = oneshot::channel();
				accessor.with(|mut access| -> wasmtime::Result<()> {
					bytes.pipe(&mut access, consumer)?;
					outcome.pipe(
						&mut access,
						OutcomeConsumer {
							sender: Some(sender),
						},
					)
				})?;
				receiver.await.map_err(|_| {
					TextError("the component ended without reporting an outcome".to_owned())
				})
			})
			.await??;

		outcome.map_err(TextError)?;
		// A poisoned lock means appending a batch panicked. The bytes appended before the
		// panic are still the component's text as far as it was taken.
		let text = std::mem::take(&mut *text.lock().unwrap_or_else(PoisonError::into_inner));
		Ok(text)
	}
}

/// Takes the bytes a component writes to its stream, and appends them to a buffer the text
/// path reads once the component has finished.
struct ByteConsumer {
	/// The bytes taken so far. Wasmtime owns the consumer while the stream is open, so the
	/// buffer is shared with the code that reads it afterwards.
	bytes: Arc<Mutex<Vec<u8>>>,
}

impl<D> StreamConsumer<D> for ByteConsumer {
	type Item = u8;

	/// Appends every byte the component has written so far, and asks for more.
	///
	/// The consumer never stops the stream early. The typed path's consumer does stop at the
	/// first statement the host refuses, but the text path cannot tell a refusal from the
	/// text alone, so it reads all of it. On the valid documents the benchmark times, both
	/// paths read everything.
	fn poll_consume(
		self: Pin<&mut Self>,
		_context: &mut Context<'_>,
		mut store: StoreContextMut<D>,
		mut source: Source<'_, Self::Item>,
		_finish: bool,
	) -> Poll<wasmtime::Result<StreamResult>> {
		let mut batch = Vec::with_capacity(source.remaining(&mut store));
		source.read(&mut store, &mut batch)?;
		self.bytes
			.lock()
			.unwrap_or_else(PoisonError::into_inner)
			.extend(batch);
		Poll::Ready(Ok(StreamResult::Completed))
	}
}

/// Receives the outcome a component writes to its future, and sends it to the code waiting
/// for it.
struct OutcomeConsumer {
	/// The sending end of the channel the outcome goes through. `None` once it has been
	/// sent.
	sender: Option<oneshot::Sender<Result<(), String>>>,
}

impl<D> FutureConsumer<D> for OutcomeConsumer {
	type Item = Result<(), String>;

	/// Reads the outcome and sends it on.
	fn poll_consume(
		mut self: Pin<&mut Self>,
		_context: &mut Context<'_>,
		mut store: StoreContextMut<D>,
		mut source: Source<'_, Self::Item>,
		_finish: bool,
	) -> Poll<wasmtime::Result<()>> {
		let mut outcome = None;
		source.read(&mut store, &mut outcome)?;
		if let (Some(outcome), Some(sender)) = (outcome, self.sender.take()) {
			// Sending fails only if the text path has stopped waiting, in which case no one
			// needs the outcome.
			let _ = sender.send(outcome);
		}
		Poll::Ready(Ok(()))
	}
}
